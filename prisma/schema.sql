CREATE TABLE IF NOT EXISTS `TaxYear` (
  `id` VARCHAR(191) NOT NULL,
  `label` VARCHAR(191) NOT NULL UNIQUE,
  `startDate` DATETIME(3) NOT NULL,
  `endDate` DATETIME(3) NOT NULL,
  `isCurrent` BOOLEAN NOT NULL DEFAULT FALSE,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `IncomingTransaction` (
  `id` VARCHAR(191) NOT NULL,
  `date` DATETIME(3) NOT NULL,
  `source` VARCHAR(191) NOT NULL,
  `description` VARCHAR(191) NOT NULL,
  `cardAmount` DOUBLE NOT NULL DEFAULT 0,
  `cashAmount` DOUBLE NOT NULL DEFAULT 0,
  `notes` TEXT NULL,
  `taxYearId` VARCHAR(191) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  FOREIGN KEY (`taxYearId`) REFERENCES `TaxYear`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `OutgoingTransaction` (
  `id` VARCHAR(191) NOT NULL,
  `date` DATETIME(3) NOT NULL,
  `seller` VARCHAR(191) NOT NULL,
  `orderNo` VARCHAR(191) NULL,
  `invoiceNo` VARCHAR(191) NULL,
  `description` VARCHAR(191) NOT NULL,
  `amount` DOUBLE NOT NULL,
  `paymentType` VARCHAR(191) NOT NULL,
  `notes` TEXT NULL,
  `taxYearId` VARCHAR(191) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  FOREIGN KEY (`taxYearId`) REFERENCES `TaxYear`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

